#!/usr/bin/env python3 -I
"""One-off generator for Sources/SextantDomain/Board/VoyagerKeys.swift (ADR 0008).

Reads docs/research/data/voyager-geometry.json (Oryx stagger, home row, side, cluster, column) and
voyager-matrix-led-map.json (matrix, LAYOUT argument order, LED points). Run from the repo root.
"""
import json

geo = {k["index"]: k for k in json.load(open("docs/research/data/voyager-geometry.json"))["keys"]}
led = json.load(open("docs/research/data/voyager-matrix-led-map.json"))
# Touch-typing fingers by column, counted from the outer (pinky) edge of each half: the two outer columns are the
# pinky's and the two inner ones the index finger's (ADR 0053). Thumb-cluster keys are the thumb's.
FINGERS = ["pinky", "pinky", "ring", "middle", "index", "index"]


def finger(g):
    if g["cluster"] == "thumb":
        return "thumb"
    # The right half counts its columns from the inner (index) side.
    return FINGERS[g["col"] if g["side"] == "left" else 5 - g["col"]]


rows = []
for k in sorted(led["keys"], key=lambda k: k["oryx_index"]):
    i = k["oryx_index"]
    g = geo[i]
    stagger = g["oryxRender"].get("translateYPercent", 0) or 0
    r, c = k["matrix"]
    lx, ly = k["led_point_xy_0_224_by_0_64"]
    qx, qy = k["kle_xy_units"]
    rows.append(
        f"        .init(index: {i}, matrixRow: {r}, matrixColumn: {c}, staggerPercent: {stagger}, "
        f"isHomeRow: {'true' if g.get('isOnHomeRow') else 'false'}, qmkPosition: .init(x: {qx}, y: {qy}), "
        f"ledPoint: .init(x: {lx}, y: {ly}), hand: .{g['side']}, finger: .{finger(g)}),"
    )
order = led["layout_macro_order_oryx_index"]
out = f"""// Generated by scripts/gen-board-definition.py from docs/research/data (ADR 0008). Do not edit by hand.
// swift-format-ignore-file

import Foundation

extension BoardDefinition {{
    static let voyagerKeys: [KeyInfo] = [
{chr(10).join(rows)}
    ]

    /// `LAYOUT_voyager(...)` argument order, as Oryx indices.
    static let voyagerLayoutOrder: [Int] = {order}
}}
"""
open("Sources/SextantDomain/Board/VoyagerKeys.swift", "w").write(out)
print(f"wrote {len(rows)} keys")
