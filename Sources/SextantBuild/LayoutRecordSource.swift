import Foundation

/// `sextant_layout.c` (ADR 0061): the layout record a build stores, and a raw-HID handler that reads it back.
///
/// Linked with `--wrap=raw_hid_receive`, the handler sits in front of `zsa/oryx`: it answers reports that start with
/// `0x53` (outside every Oryx command id) and passes every other report on unchanged. Request `53 01 <offset hi>
/// <offset lo>`; reply `53 01 <status> <size hi> <size lo> <offset hi> <offset lo> <count> <count bytes, at most 24>`,
/// status 0 for data, 1 for an offset at or past the end, 2 for an unknown request. It only reads.
enum LayoutRecordSource {
    /// The lines the keymap's `rules.mk` gains. `QMKBuild` passes `EXTRALDFLAGS` on make's command line, and a command
    /// line variable ignores a plain `+=` in a makefile, so the wrap is appended with `override`.
    static let rules = """
        SRC += sextant_layout.c
        override EXTRALDFLAGS += -Wl,--wrap=raw_hid_receive

        """

    /// The C file for an encoded record (``LayoutRecord/encoded()``), 16 bytes per line.
    static func render(_ record: [UInt8]) -> String {
        let rows = stride(from: 0, to: record.count, by: 16).map { start in
            "    " + record[start..<min(start + 16, record.count)].map { String(format: "0x%02X", $0) }.joined(separator: ", ")
        }
        return "\(header)\n\nstatic const uint8_t sextant_layout[\(record.count)] = {\n\(rows.joined(separator: ",\n"))\n};\n\(handler)"
    }

    private static let header = """
        // Generated by Sextant (ADR 0061). The layout this firmware was built from, so Sextant on any Mac can read it back
        // over raw HID. Linking with --wrap=raw_hid_receive puts this in front of zsa/oryx: reports that start with 0x53 are
        // answered here, every other report goes on to zsa/oryx unchanged.
        #include QMK_KEYBOARD_H
        #include <string.h>
        #include "raw_hid.h"

        #ifndef RAW_EPSIZE
        #    define RAW_EPSIZE 32
        #endif
        """

    private static let handler = """

        void __real_raw_hid_receive(uint8_t *data, uint8_t length);
        void __wrap_raw_hid_receive(uint8_t *data, uint8_t length);

        void __wrap_raw_hid_receive(uint8_t *data, uint8_t length) {
            if (length < 4 || data[0] != 0x53) {
                __real_raw_hid_receive(data, length);
                return;
            }
            uint8_t reply[RAW_EPSIZE];
            memset(reply, 0, sizeof(reply));
            reply[0] = 0x53;
            reply[1] = data[1];
            if (data[1] != 0x01) {
                reply[2] = 0x02; // unknown request
            } else {
                uint16_t size   = (uint16_t)sizeof(sextant_layout);
                uint16_t offset = (uint16_t)((data[2] << 8) | data[3]);
                reply[3] = (uint8_t)(size >> 8);
                reply[4] = (uint8_t)(size & 0xFF);
                reply[5] = data[2];
                reply[6] = data[3];
                if (offset >= size) {
                    reply[2] = 0x01; // past the end
                } else {
                    uint16_t count = size - offset;
                    if (count > RAW_EPSIZE - 8) count = RAW_EPSIZE - 8;
                    reply[7] = (uint8_t)count;
                    memcpy(reply + 8, sextant_layout + offset, count);
                }
            }
            raw_hid_send(reply, RAW_EPSIZE);
        }

        """
}
